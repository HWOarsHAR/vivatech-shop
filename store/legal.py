class PdfUnavailable(Exception):
    """PDF нельзя собрать (нет reportlab или шрифта с кириллицей)."""


def get_doc(slug):
    """Документ с подставленными реквизитами или None."""
    raw = DOCS.get(slug)
    if raw is None:
        return None
    return {
        "slug": slug, "title": raw["title"], "filename": raw["filename"], "date": DOC_DATE,
        "sections": [{"heading": h, "paragraphs": [p.format(**COMPANY) for p in ps]}
                     for h, ps in raw["sections"]],
    }


# ---------- TXT ----------
def to_txt(doc) -> bytes:
    lines = [doc["title"].upper(), f"Редакция от {doc['date']}", ""]
    for s in doc["sections"]:
        lines += [s["heading"], ""] + [p + "\n" for p in s["paragraphs"]]
    # utf-8-sig: «Блокнот» старых версий Windows корректно определяет кодировку
    return "\r\n".join(lines).encode("utf-8-sig")


# ---------- ODT (OpenDocument) — архив из XML, внешние библиотеки не нужны ----------
_NS = ('xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" '
       'xmlns:style="urn:oasis:names:tc:opendocument:xmlns:style:1.0" '
       'xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0" '
       'xmlns:fo="urn:oasis:names:tc:opendocument:xmlns:xsl-fo-compatible:1.0"')


def to_odt(doc) -> bytes:
    body = [f'<text:p text:style-name="T">{escape(doc["title"])}</text:p>',
            f'<text:p text:style-name="D">Редакция от {escape(doc["date"])}</text:p>']
    for s in doc["sections"]:
        body.append(f'<text:h text:style-name="H" text:outline-level="2">{escape(s["heading"])}</text:h>')
        body += [f'<text:p text:style-name="P">{escape(p)}</text:p>' for p in s["paragraphs"]]
    content = (
        f'<?xml version="1.0" encoding="UTF-8"?><office:document-content {_NS} office:version="1.2">'
        '<office:automatic-styles>'
        '<style:style style:name="T" style:family="paragraph"><style:paragraph-properties fo:text-align="center" fo:margin-bottom="0.3cm"/>'
        '<style:text-properties fo:font-size="16pt" fo:font-weight="bold"/></style:style>'
        '<style:style style:name="D" style:family="paragraph"><style:paragraph-properties fo:text-align="center" fo:margin-bottom="0.4cm"/>'
        '<style:text-properties fo:font-size="10pt" fo:color="#666666"/></style:style>'
        '<style:style style:name="H" style:family="paragraph"><style:paragraph-properties fo:margin-top="0.4cm" fo:margin-bottom="0.15cm"/>'
        '<style:text-properties fo:font-size="13pt" fo:font-weight="bold"/></style:style>'
        '<style:style style:name="P" style:family="paragraph"><style:paragraph-properties fo:text-align="justify" fo:margin-bottom="0.15cm"/>'
        '<style:text-properties fo:font-size="11pt"/></style:style>'
        f'</office:automatic-styles><office:body><office:text>{"".join(body)}</office:text></office:body></office:document-content>')
    manifest = (
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<manifest:manifest xmlns:manifest="urn:oasis:names:tc:opendocument:xmlns:manifest:1.0" manifest:version="1.2">'
        '<manifest:file-entry manifest:full-path="/" manifest:version="1.2" manifest:media-type="application/vnd.oasis.opendocument.text"/>'
        '<manifest:file-entry manifest:full-path="content.xml" manifest:media-type="text/xml"/></manifest:manifest>')
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        # mimetype должен идти первым и быть без сжатия — требование формата ODF
        z.writestr(zipfile.ZipInfo("mimetype"), "application/vnd.oasis.opendocument.text")
        z.writestr("META-INF/manifest.xml", manifest, zipfile.ZIP_DEFLATED)
        z.writestr("content.xml", content, zipfile.ZIP_DEFLATED)
    return buf.getvalue()


# ---------- PDF (reportlab + системный шрифт с кириллицей) ----------
def _find_fonts():
    win = os.path.join(os.environ.get("WINDIR", r"C:\Windows"), "Fonts")
    pairs = [
        (os.path.join(win, "arial.ttf"), os.path.join(win, "arialbd.ttf")),
        ("/Library/Fonts/Arial.ttf", "/Library/Fonts/Arial Bold.ttf"),
        ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"),
        ("/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
         "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"),
    ]
    for regular, bold in pairs:
        if os.path.exists(regular) and os.path.exists(bold):
            return regular, bold
    return None, None


def to_pdf(doc) -> bytes:
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import ParagraphStyle
        from reportlab.lib.units import mm
        from reportlab.pdfbase import pdfmetrics
        from reportlab.pdfbase.ttfonts import TTFont
        from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer
    except ImportError:
        raise PdfUnavailable("Для PDF установите библиотеку: pip install reportlab")
    regular, bold = _find_fonts()
    if not regular:
        raise PdfUnavailable("Не найден шрифт с кириллицей (Arial или DejaVu Sans)")
    if "DocFont" not in pdfmetrics.getRegisteredFontNames():
        pdfmetrics.registerFont(TTFont("DocFont", regular))
        pdfmetrics.registerFont(TTFont("DocFont-Bold", bold))

    title = ParagraphStyle("t", fontName="DocFont-Bold", fontSize=16, leading=20, alignment=1, spaceAfter=4)
    date = ParagraphStyle("d", fontName="DocFont", fontSize=9, leading=12, alignment=1, spaceAfter=10,
                          textColor="#666666")
    head = ParagraphStyle("h", fontName="DocFont-Bold", fontSize=12, leading=15, spaceBefore=10, spaceAfter=4)
    para = ParagraphStyle("p", fontName="DocFont", fontSize=10, leading=14, alignment=4, spaceAfter=4)

    story = [Paragraph(escape(doc["title"]), title), Paragraph(f"Редакция от {escape(doc['date'])}", date)]
    for s in doc["sections"]:
        story.append(Paragraph(escape(s["heading"]), head))
        story += [Paragraph(escape(p), para) for p in s["paragraphs"]]
        story.append(Spacer(1, 2))

    def footer(canvas, _doc):  # номер страницы внизу
        canvas.setFont("DocFont", 8)
        canvas.drawCentredString(A4[0] / 2, 10 * mm, f"{COMPANY['brand']} · {doc['title']} · стр. {canvas.getPageNumber()}")

    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm, topMargin=18 * mm,
                      bottomMargin=20 * mm, title=doc["title"], author=COMPANY["name"]).build(
        story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()
